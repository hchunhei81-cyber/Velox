use crate::ast::Ty;
use crate::ffi::FfiFn;

pub fn generate_wrapper(libname: &str, fns: &[FfiFn]) -> String {
    let mut out = String::new();
    out.push_str("# Auto-generated by veloxc --py. Do not edit.\n");
    out.push_str("import ctypes, os\n\n");
    out.push_str(&format!(
        "_lib = ctypes.CDLL(os.path.join(os.path.dirname(os.path.abspath(__file__)), {:?}))\n\n",
        libname
    ));

    for f in fns {
        let args: Vec<&str> = f.params.iter().map(argtype).collect();
        out.push_str(&format!(
            "_lib.{n}.argtypes = [{a}]\n_lib.{n}.restype = {r}\n\n",
            n = f.name,
            a = args.join(", "),
            r = restype(&f.ret)
        ));

        let params: Vec<String> = (0..f.params.len()).map(|i| format!("a{}", i)).collect();
        let call_args: Vec<String> = (0..f.params.len()).map(|i| format!("a{}", i)).collect();
        out.push_str(&format!(
            "def {n}({p}):\n    return _lib.{n}({a})\n\n",
            n = f.name,
            p = params.join(", "),
            a = call_args.join(", ")
        ));
    }
    out
}

fn argtype(t: &Ty) -> &'static str {
    match t {
        Ty::I64 => "ctypes.c_int64",
        Ty::F64 => "ctypes.c_double",
        Ty::Str => "ctypes.c_char_p",
        Ty::Void => "None",
    }
}
fn restype(t: &Ty) -> &'static str {
    match t {
        Ty::Void => "None",
        _ => argtype(t),
    }
}
